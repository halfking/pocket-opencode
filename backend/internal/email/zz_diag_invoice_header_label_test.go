package email

import "testing"

// 「发票抬头」被当成对方单位，导致同一张票产生两个文件名。
//
// 真实证据（2026-10-04 磁盘产物）：
//
//	其他-云服务开票中心-1280.00-2026-09-28.pdf
//	其他-云服务开票中心-发票抬头-1280.00-2026-09-28.pdf
//
// 两份**字节完全相同**（md5 633f5b8b…），即同一张票被命名了两次，
// 而第二份的「对方单位」是「发票抬头」——一个**列头**，不是单位名。
//
// 成因：`invoiceLabelWords`（invoice.go 的列头表）收录了「发票号码」
// 「开票日期」「纳税人识别号」等，唯独**漏了「发票抬头」**。于是
// `isInvoiceLabelWord("发票抬头")` 返回 false，
// `sellerFromFollowingLines` 就不把它跳过、不计入尝试次数，
// 直接当成候选单位名收下了。
//
// 需求原文要 `{费用类型}-{对方单位}-{金额}-{日期}.pdf`。这一列
// 收进列头，文件名才符合需求，也才不会出现「一张票两个名字」。
func TestInvoiceHeaderIsRecognizedAsColumnLabel(t *testing.T) {
	// 「发票抬头」是发票邮件里最标准的单位名列头之一，必须被认成列头。
	if !isInvoiceLabelWord("发票抬头") {
		t.Error("isInvoiceLabelWord(\"发票抬头\") = false —— " +
			"它被当成了对方单位，于是同一张票出现了两个文件名" +
			"（实测：其他-云服务开票中心-1280.00-2026-09-28.pdf 与 " +
			"其他-云服务开票中心-发票抬头-1280.00-2026-09-28.pdf 字节相同）")
	}

	// 防止「修一个漏一片」：同族的抬头/单位名列头都该被认成列头。
	// 这些是真实发票模板里与「发票抬头」并列或近似的叫法。
	for _, w := range []string{
		"发票抬头", "抬头发票方", "销售方名称", "开票方", "销方名称",
		"销售名称", "购买方名称", "购方名称", "收款方名称", "开票单位",
	} {
		if !isInvoiceLabelWord(w) {
			t.Logf("注意：%q 也未被认成列头（与「发票抬头」同族的叫法）", w)
		}
	}

	// 反向：真正的单位名不能被误判成列头，否则正确数据会被丢掉。
	for _, w := range []string{
		"腾讯云计算（北京）有限责任公司", "浙江沪杭甬高速公路股份有限公司",
		"杭州创客家投资管理有限公司", "云服务开票中心",
	} {
		if isInvoiceLabelWord(w) {
			t.Errorf("isInvoiceLabelWord(%q) = true —— 真实单位名被当成列头，seller 会被丢掉", w)
		}
	}
}
