package server

// sse_write.go — §946：SSE（流式响应）的「写出去」。
//
// # ⚠ 为什么 SSE 要单独一套（不能套 writeJSON 的「先编码后写状态」）
//
//	普通 JSON 响应：状态行提交后，写失败**没法**再改状态码 ⇒ 只能留痕。
//	SSE　　　　　 ：整条响应**就是**一串写操作 ⇒ 写失败 = 客户端断开
//	　　　　　　　 = 这条流已经死了 ⇒ ⇒⇒ 继续写只会一次次失败
//	　　　　　　　 （而且每次都刷一条错误日志）⇒ ⇒⇒ ⇒ 必须能**中断**这条流。
//
//	⇒ ⇒⇒ 而且 SSE 是**流式**的 ⇒ 「先编码后写状态」会把整条流攒进内存
//	⇒ ⇒⇒ ⇒ 所以 SSE 走「写 + 留痕 + 由调用方中断」这条路。
//
// # ⚠ 为什么留痕放在 helper 里（而不是每个调用点各写一遍）
//
//	15 处调用点（§946 实测）⇒ ⇒⇒ 每处各写一遍 ⇒ 15 份复制粘贴
//	⇒ ⇒⇒ ⇒ 而复制粘贴的日志文案**会互相漂移**（一处改了其余 14 处没改
//	⇒ ⇒⇒ ⇒ ⇒ 于是「SSE 写失败」这个信号就变得没法 grep 了）。
//
//	★ 同族教训（§945）：**同一段逻辑抄 N 遍 ⇒ 同一缺陷必然出现在 N 处**
//	⇒ ⇒⇒ ⇒ 所以收成一个 helper。

import (
	"fmt"
	"log"
	"net/http"
)

// s946SSEWritef 写一段 SSE 文本。
//
// ⚠ 返回 error 是为了让调用方**中断**这条流（写失败 = 客户端没了）。
//
// ⚠ 失败时**已经记了日志** ⇒ 调用方不必再记一遍（也不该记两遍）。
func s946SSEWritef(w http.ResponseWriter, format string, args ...any) error {
	if _, err := fmt.Fprintf(w, format, args...); err != nil {
		log.Printf("[WARN] SSE 事件写出失败（客户端可能已断开）：%v", err)
		return err
	}
	return nil
}
