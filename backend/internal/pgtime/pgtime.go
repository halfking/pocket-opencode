// Package pgtime 是「PG 边界的时刻刻度」的**单一事实源**。
//
// # 这条纪律是什么
//
//	凡是**写进 PG 的时刻**，在**取值的那一刻**就要向下截断到微秒，
//	这样「返回给调用方的那个值」与「库里真正存着的那个值」**逐字相同**。
//
// # 为什么是微秒，为什么是向下
//
//	PG 的 `timestamptz` **物理上只能存微秒**。而仓里所有写入走的是
//	**pgx 参数绑定**，实测（PG 17.11 + pgx v5，§966 真机读数）：
//
//	| 写进去的亚微秒尾 | 参数绑定（pgx） | SQL 字面量（PG 自己解析） |
//	|---|---|---|
//	| 0ns    | ±0      | ±0      |
//	| 300ns  | −300ns（舍） | −300ns（舍） |
//	| 500ns  | −500ns（舍） | −500ns（舍） |
//	| 700ns  | **−700ns（舍）** | **+300ns（进位）** |
//	| 999999ns | −999ns（舍） | +1ns（进位） |
//
//	⇒ ⇒ ★★ **两条路径的行为不同**，而仓里的写入**全部走参数绑定**：
//	**pgx 在客户端编码时就已经向下截断了** ⇒ PG 根本没见到亚微秒部分
//	⇒ ⇒ ⇒ **「PG 会把写进去的值四舍五入」这句话对参数绑定路径是错的**
//	（它只对 SQL 字面量路径成立 —— 见 pgtime 包的 pg 驱动判据）。
//	⇒ ⇒ ⇒ 而「向下截断」这个**结论**不变，但**理由**要换成：
//	**驱动（pgx）会再向下截断一次** ⇒ 若写入侧用四舍五入，
//	落盘值仍会带亚微秒部分 ⇒ 驱动再截一次 ⇒ 内存值 != 库值。
//
//	⚠⚠ **这一点必须被钉住**：前提一旦被改写，后人就会依据错误前提做决策
//	（§964 的注释就写着「PG 用 round-half-to-even ⇒ PG 存它时还会再动一次」）
//	⇒ 所以 `pgtime` 包里有一条**连真 PG** 的判据盯着驱动行为
//	（pgx 升级导致行为变化时，那条判据会红 ⇒ 前提被强制重新审视）。
//
// # 为什么这个包存在（而不是每个 store 各抄一份）
//
//	§964 把截断逻辑写在了 `internal/meeting` 包里（`pgTruncate`/`pgNow`）。
//	⇒ 那份约定只对 meeting 生效 ⇒ 下一个 store 会照抄一份
//	⇒ ⇒ 抄到第 N 份时**迟早有一份抄错** ⇒⇒⇒ 「一个常量服务两个调用方」
//	的同族病（§965 那条「病是写死不是写错」的反面：这里是**复制**不是**共享**）。
//	⇒ ⇒ ⇒ 收编成一个包，让「时刻的刻度」**只有一处**可查。
//
// # 用法
//
//	now := pgtime.Now()        // 取「写进 PG 的那一刻」
//	sent := pgtime.Truncate(t) // 把外部给来的时刻折算到同一刻度
//
//	⚠ 边界参数（查询里的 `timestamp < $1` 之类）**不需要**手工截断：
//	驱动在编码时会把它们**一并**向下截断 ⇒ 存储值与边界值天然同刻度。
package pgtime

import "time"

// Truncate 把一个时刻**向下**截断到微秒。
//
// ⚠ 是**向下**（floor）而不是四舍五入（round）—— 理由见包注释：
//
//	驱动（pgx）在编码时会再向下截断一次
//	⇒ 若这里用 round，落盘值仍可能带亚微秒部分 ⇒ 内存值 != 库值。
//
// ⚠ `Time.Truncate` 以**零时刻**为基准向下取整，而「零时刻 → Unix 纪元」
//
//	恰好是 62135596800000000 µs（微秒的整数倍）
//	⇒ ⇒ 对纪元之后的时刻，按零时刻取整 == 按纪元取整（PG 自己的取整基准）。
//
// ⚠ 截断会丢掉 <1µs ⇒ 对业务毫无影响（会议时间点的精度需求是分钟级）。
func Truncate(t time.Time) time.Time {
	return t.Truncate(time.Microsecond)
}

// Now 取「写进 PG 的那一刻」的时间戳，**截断到微秒**。
//
// ⇒ 凡是**写进 PG 的时间戳**都必须走它（别再直接调 `time.Now()`），
//
//	否则「写进去的值」与「返回给调用方的值」会差一个亚微秒量。
//
// ⚠ 用它**取 ID** 是错的：`UnixNano()` 取的是 epoch 纳秒，
//
//	截断它反而会削弱唯一性（会议 ID 的发号器见 meeting 包 `nextMeetingID`）。
func Now() time.Time {
	return Truncate(time.Now())
}
