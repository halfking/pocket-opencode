import assert from 'node:assert/strict'
import { test } from 'node:test'
import { fixture } from '../../../test-support/notes-sqlite-fixture.mjs'

const path = '/src/features/notes/legacy-note-claim.ts'
const bind = f => f.db.bindOperation(f.db.captureOperation({ kind: 'local-edit' }))
const localAsset = (f, id, { workspace = 'workspace', source = 'manual', mode = 'e2ee_local_first',
  body = '<p>original HTML</p>', encrypted = 0 } = {}) => f.db.run(`
    INSERT INTO local_assets(id,workspace_id,kind,title,body_text,body_encrypted,meta_json,source,sync_mode,created_at,updated_at)
    VALUES (?,?,'note','Original title',?,?,?, ?, ?,17,31)`, [id, workspace, body, encrypted,
  JSON.stringify({ tags: ['local'], links: ['Origin'], enexId: 'archive-1', password: 'local metadata' }), source, mode])

test('explicit claim links a file-backed note without touching its original or scheduling upload', () => fixture(async f => {
  await f.setMode('local')
  const fullBody = '完整文件正文\n'.repeat(3600)
  const saved = await f.notes.createNote({ title: 'Local', content: fullBody, workspaceId: 'workspace',
    media: [{ kind: 'audio', blob: new Blob(['local recording'], { type: 'audio/webm' }) }] }, { backgroundCloud: false })
  assert.equal(saved.storageTier, 'file')
  const original = await f.db.queryOne('SELECT * FROM local_notes WHERE id=?', [saved.id])
  const files = await f.db.query('SELECT * FROM local_note_files WHERE note_id=?', [saved.id])
  assert.ok(files.length >= 2)
  const { canClaimLegacyNote, prepareLegacyNoteClaim } = await f.loadModule(path)
  assert.equal(await canClaimLegacyNote('note', saved.id), true)
  const prepared = await prepareLegacyNoteClaim('note', saved.id)
  assert.equal(prepared.workspaceId, 'workspace')
  assert.equal(f.count('local_portal_notes'), 0)
  await prepared.claim()
  assert.equal(await canClaimLegacyNote('note', saved.id), false)
  assert.deepEqual(await f.db.queryOne('SELECT * FROM local_notes WHERE id=?', [saved.id]), original)
  assert.deepEqual(await f.db.query('SELECT * FROM local_note_files WHERE note_id=?', [saved.id]), files)
  assert.equal(f.count('local_portal_outbox'), 0)
  const store = f.portalNotesStore(bind(f))
  const projection = await store.find('note', saved.id)
  const item = await store.decode(projection.item_json)
  assert.equal(item.payload.content, fullBody)
  assert.equal(item.client_updated_at, new Date(original.updated_at).toISOString())
  assert.equal(item.epoch, null)
  assert.ok(!JSON.stringify(item).includes('local recording'))
  assert.equal(f.requests.length, 0)

  await f.login('B')
  assert.equal(await f.notes.getNote(saved.id, false, 'workspace'), null)
  await assert.rejects(prepareLegacyNoteClaim('note', saved.id), /already owned/)
  await f.login('A')
  await f.setMode('local')
  await f.notes.updateNote(saved.id, { title: 'Explicit later edit' }, 'workspace')
  const [operation] = await f.portalNotesStore(bind(f)).pending()
  assert.equal(operation.ext_id, item.ext_id)
  assert.equal(operation.payload.content, fullBody)
}))

test('PKM and ENEX claims preserve format and original encryption without adopting another workspace', () => fixture(async f => {
  await f.setMode('local')
  const markdown = '历史 Markdown 正文\n'.repeat(8000)
  const cipher = await f.crypto.encryptString(markdown)
  await localAsset(f, 'html')
  await localAsset(f, 'enex', { source: 'enex_import', encrypted: 1, body: cipher })
  await localAsset(f, 'other', { workspace: 'another-workspace' })
  await localAsset(f, 'cloud', { mode: 'cloud_authoritative' })
  const { prepareLegacyNoteClaim, canClaimLegacyNote } = await f.loadModule(path)
  assert.equal(await canClaimLegacyNote('asset', 'other'), false)
  assert.equal(await canClaimLegacyNote('asset', 'cloud'), false)
  await assert.rejects(prepareLegacyNoteClaim('asset', 'other'), /unavailable/)
  await (await prepareLegacyNoteClaim('asset', 'html')).claim()
  await (await prepareLegacyNoteClaim('asset', 'enex')).claim()
  const store = f.portalNotesStore(bind(f))
  const html = await store.decode((await store.find('asset', 'html')).item_json)
  const enexRow = await store.find('asset', 'enex')
  const enex = await store.decode(enexRow.item_json)
  assert.equal(html.payload.format, 'html')
  assert.equal(html.payload.content, '<p>original HTML</p>')
  assert.match(enexRow.item_json, /^e1:/)
  assert.equal(enex.payload.format, 'markdown')
  assert.equal(enex.payload.import_id, 'archive-1')
  assert.equal(enex.payload.content, markdown)
  assert.ok(!('password' in enex.payload))
  assert.equal((await f.db.queryOne("SELECT body_text FROM local_assets WHERE id='enex'")).body_text, cipher)
  assert.equal(f.count('local_portal_outbox'), 0)
  await f.login('B')
  assert.equal(await f.assetStore.getForWorkspace('enex', 'workspace'), null)
  assert.equal(await f.assetStore.getForWorkspace('html', 'workspace'), null)
}))

test('the same timestamp cannot mask an edit and no claim crosses an account activation', () => fixture(async f => {
  const { prepareLegacyNoteClaim } = await f.loadModule(path)
  await localAsset(f, 'edit')
  const open = await prepareLegacyNoteClaim('asset', 'edit')
  await f.db.run("UPDATE local_assets SET body_text='another edit' WHERE id='edit'")
  await assert.rejects(open.claim(), /portal_notes_write_conflict/)
  assert.equal(f.count('local_portal_notes'), 0)
  const interrupted = await prepareLegacyNoteClaim('asset', 'edit')
  await f.login('B')
  await assert.rejects(interrupted.claim(), { name: 'AbortError' })
  assert.equal(f.count('local_portal_notes'), 0)
  const ready = await prepareLegacyNoteClaim('asset', 'edit')
  const competing = await prepareLegacyNoteClaim('asset', 'edit')
  const results = await Promise.allSettled([ready.claim(), competing.claim()])
  assert.equal(results.filter(result => result.status === 'fulfilled').length, 1)
  assert.equal(f.count('local_portal_notes'), 1)
  assert.equal(f.count('local_portal_outbox'), 0)
}))

test('an unavailable historical body and a tombstone cannot be claimed', () => fixture(async f => {
  const { prepareLegacyNoteClaim, canClaimLegacyNote } = await f.loadModule(path)
  await f.db.run(`INSERT INTO local_notes(id,workspace_id,content,encrypted_content,created_at,updated_at,storage_tier,body_path)
    VALUES ('missing','workspace','short summary',0,17,31,'file','sqlite:missing.txt')`)
  await localAsset(f, 'deleted')
  const pending = await prepareLegacyNoteClaim('asset', 'deleted')
  await f.db.run("UPDATE local_assets SET deleted_at=48 WHERE id='deleted'")
  assert.equal(await canClaimLegacyNote('asset', 'deleted'), false)
  await assert.rejects(pending.claim(), /portal_notes_write_conflict/)
  await assert.rejects(prepareLegacyNoteClaim('note', 'missing'), /Complete historical note body is unavailable/)
  assert.equal(f.count('local_portal_notes'), 0)
  assert.equal(f.count('local_portal_outbox'), 0)
  assert.equal(f.count('local_notes'), 1)
}))
