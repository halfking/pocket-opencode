/**
 * refine-prompt.ts — 前端**回落路径**专用的精校提示词（§54）。
 *
 * ── 为什么这里会有一份提示词 ──
 *
 * 精校有两条实现：
 *   ① 服务端 `POST /api/meetings/{id}/refine` → `buildRefinePrompt`（Go）
 *   ② 前端 `fallbackRefine()` → `/api/llm/chat`（TS，就是本文件）
 *
 * ② 是①**失败时**的兜底（`meetings.ts` 的 catch 分支）。它必须独立存在：
 * 后端没配 LLM（503）、后端超时/报错（502）、客户端超时，都是真实可达的
 * 触发路径 —— 而 `/api/llm/chat` 只在 `llm not configured` 时才会自己失败。
 *
 * ⚠ 这个触发面不小：前端给精校的客户端预算是 150s（`MEETING_REFINE_TIMEOUT_MS`），
 *   而 llmgateway 的 `ResponseHeaderTimeout` 实测只有 60s（§44：`auto` 路由
 *   落到 deepseek-v4-flash 时首字节 24~142s）⇒ **后端先超时返 502**
 *   ⇒ 前端必走这里。所以「兜底质量」不是边角情况，它是这条链路的主路径之一。
 *
 * ── 为什么这份提示词曾经是错的（§54 发现 C）──
 *
 * ①在2026-10-07 被实测重写过（§35）：根因词「**润色**」被删、四条禁令补上、
 * 「不得改动数字」补上。**② 一字未动**，于是它还停在旧版本上：
 *
 *   - 「请润色」⇒ 实测会把**完全正确**的句子改写掉、把 CI 改成 101、
 *     还会加原文没有的括注。对会议纪要产品，这比不纠错严重得多：
 *     **误改用户发现不了**（他不知道原文是什么），漏修一眼能看出来。
 *   - `\"action_items\":[]`、`\"todos\":[]` 是**空数组**范例 ⇒ 模型照抄返回空
 *     ⇒ 「时间点自动加入计划日程」在回落路径上同样没有输入。
 *     §54 用真网关在①上实测过：改掉空数组范例后，同一段转写的
 *     `action_items` 从 `[]` 变成 3 条，其中一条带 `due:"十一月底之前"`。
 *   - 没有会议元数据（主题/参会人）⇒ 没有术语表，`页百零一→CI`、
 *     `林兰→林岚` 这类错误在这条路径上修不了。
 *
 * 这与 §53 修掉的 `filenameForMimeType`（两处各写一份，已经漂）是同一族：
 * **同一份契约写两遍，漂移只是时间问题。**
 *
 * ── 怎么防止再漂 ──
 *
 * 跨语言没法共享同一份常量（Go 与 TS），所以这里导出 `REFINE_PROMPT_CONTRACT`
 * 作为**契约清单**，由 `api/__tests__/refine-prompt-parity.test.ts` 断言
 * **本文件与 `server_meeting.go` 的 `buildRefinePrompt` 同时包含每一条**。
 * 清单与判据同源 ⇒ 下一个人加契约项只改一处，两份提示词都会被点名。
 */

/**
 * 精校提示词的契约清单在 `api/__tests__/refine-prompt-parity.test.mjs`
 * （本文件不导出它 —— 一个只有测试引用的导出会被 `check:dead-features`
 * 当成未接线的死能力，那道门是对的）。
 *
 * 把清单放在测试里而不是这里，**不影响防漂**：门拿这份清单同时点名
 * 本文件与 `server_meeting.go` 的 `buildRefinePrompt`，两边都必须满足。
 * 加契约项只改测试一处，两份提示词一起被点名。
 *
 * ⚠ 清单的每一条都来自**真网关实测**，不是预防性设计（§35 / §54）：
 *  - 「润色」是 §35 实测出的根因词
 *  - 「不得改动数字」是第一版重写时漏掉、复测发现模型在猜数字后补上的
 *  - `action_items`/`todos` 的**非空**范例是 §54 实测出的（空数组 ⇒ 返回空）
 *  - 「特别地」那段禁令堵的是 §35 实测出的**具体误解**：
 *    模型会把转写里的人名「对齐」进名单（张伟/李娜 → 赵敏/孙磊），
 *    只写「不要替换成不对应的词」它会理解成「赵敏在名单里所以是对应的」。
 */

/** 回落路径能拿到的会议元数据（与服务端 meetingMetaIn 同名同义）。 */
export interface RefineMeta {
  title?: string
  participants?: string[]
  location?: string
  /**
   * 会议主题（§138.3）。此前**两侧都没有**这个字段 ⇒ 主题里的专有名词
   * 到不了精校。回落路径是**降级分支**，它拿不到上下文时纠正能力最弱，
   * 所以两边必须同时补 —— 只补服务端会让降级路径继续抄错专有名词。
   */
  topic?: string
}

/**
 * 拼回落路径的精校提示词。
 *
 * 与服务端 `buildRefinePrompt` 同契约；差别只在它没有 langHint
 * （回落路径拿不到目标语言，也没在回落里做中英对照 —— 原实现也没有，
 * 不在这里凭空加一条没验过的要求）。
 */
export function buildFallbackRefinePrompt(transcript: string, meta?: RefineMeta): string {
  return `${termHint(meta)}以下是会议录音的自动转写结果，其中可能有语音识别错误。请**纠正明显的识别错误**，并严格返回 JSON：{"refined_transcript":"","translations":{},"structured_minutes":{"agenda":[],"decisions":[],"action_items":[{"text":"","assignee":"","due":""}],"next_meeting":""},"todos":[{"text":"","assignee":"","due":""}]}

★ structured_minutes.action_items 与 todos 的要求（缺了它们，下游拿不到任何东西）：
1. 只放转写里**真实提到、且需要有人去做**的事；纯讨论、闲聊、状态汇报不要放。
2. **text 用用户原话里的动作**（如「准备对比表」「确认预算」），不要改写成更正式的说法。
3. **due 保留用户原话**（如「下周三下午三点」「十一月底之前」），**不要自己换算成日期**；转写里没提期限就留空字符串。
   ★ **due 必须能脱离上下文独立成立**：转写里的「那之前」「到时候」「之后」这类**指代**，要换成它所指的具体时间（如「对比表要在那之前准备好」且上文是「评审会定在下周三下午三点」⇒ due 写「下周三下午三点之前」）。实在指不出具体时间就留空字符串。
4. assignee 填转写里明确指派的人；没指派就留空字符串，不要猜。
5. 没有可提取的事项时返回空数组 [] —— 但请先确认转写里真的没有。
6. action_items 与 todos 内容一致即可（下游两处都读）。

★ next_meeting 的要求（用户需求：时间点自动加入计划日程）：
1. 若转写里提到**下一次**会议/评审/约见的时间点，填成一句带该时间点的短句（可含主题，如「下周三下午三点客户评审会」）。
2. **保留用户原话**里的时间表述，不要自己换算成日期。
3. 只填**下次**那一个；本次会议自己的时间**不算**。
4. 没有下次会议时间点时填空字符串 ""，不要填 null，也不要编一个。

refined_transcript 的硬性要求：
1. **只改错，不改写**。句子结构、措辞、信息量必须与原文一致；拿不准的地方**原样保留**，不要为了通顺而调整。
2. **不得增加原文没有的内容**（包括括注、解释、补充说明）。
3. **不得删除原文有的内容**。
4. **不得改动数字**。你无法从转写判断哪个数字才是对的，猜的那一下必然是错的。
5. 只纠正能从上下文确定的错误：英文单词/缩写/标识符被听错（如字母被读成中文谐音、下划线被读成词）、专有名词、同音字。
6. 保留每行开头的 [说话人] 标记，格式与原文一致。

转写：
${transcript}`
}

/**
 * 把会议元数据当术语表拼进提示词。
 *
 * 与服务端同法（§30/§35）：`页百零一→CI`、`接单→git`、`countedgettotal→calculateTotal`
 * 这类错误语言模型无从推断，但**给了名单/主题就有了依据**。
 *
 * ⚠ 「特别地」那段不是预防性设计，是配对实验逼出来的（§35）：
 *   转写「张伟和李娜都会参加」（**完全正确**）+ 名单「赵敏、孙磊」（转写里一个都没有）
 *   → 模型把转写里的人名**对齐**进了名单，改成「赵敏和孙磊都会参加」。
 *   那是**把正确的内容改成了错的**，而用户看不出来。
 *   第一版禁令只说「不要替换成不对应的词」，模型把「张伟→赵敏」理解成
 *   「对应的」（赵敏在名单里）⇒ 绕过了禁令。**禁令要堵住这个具体误解。**
 *
 * 参会人列表是用户手填的，空串/空格是常态 —— 直接 ", , 张伟" 拼进去会让
 * 这份「可信上下文」本身变脏，模型也会顺着脏上下文猜。
 */
function termHint(meta?: RefineMeta): string {
  const parts: string[] = []
  const title = meta?.title?.trim()
  if (title) parts.push(`会议主题：${title}。`)
  const people = (meta?.participants ?? []).map((p) => p?.trim() ?? '').filter((p) => p !== '')
  if (people.length > 0) parts.push(`参会人：${people.join('、')}。`)
  // ⚠ 2026-10-07（§64.6）：`location` 一直在请求体里（前端 `meeting-recording-finalize.ts`
  //  确实发 `location: meeting?.location`），而服务端 `buildRefinePrompt` 只读
  //  Title 与 Participants ⇒ **地点被发过来又静静丢掉**，与 §48 那三项同型。
  //  加进来的依据是**实测无害**（真网关 4/4 样本：把转写里没有的地点词
  //  「星海科技总部三楼」放进元数据，0/4 被塞进精校结果，原有纠正 4/4 未退化）。
  //  ⚠ 只测到「无害」，**没测到「有益」** —— 本轮素材里没有地点被听错的样本。
  //  真正要确认它有用，得有一段「地点被听错」的真实转写。
  const location = meta?.location?.trim()
  if (location) parts.push(`会议地点：${location}。`)
  // ⚠ 2026-10-07（§138.3）：主题里装的是**专有名词**，而这正是 ASR 错得最多的
  //   一类（实测：同一段音频，mimo 转对「悬界芯片」，minimax 转成「玄介芯片」）。
  //
  // ⚠⚠ 2026-10-07（§146）**更正**：标签用「会议议题」而不是「会议主题」，
  //   原先的理由是「共用标签会让模型以为是同一条信息出现两次」。那条理由**没被测过**，
  //   而 §146 的 A/B 顺手**证伪了它旁边那个更强的说法**（产品名只能放主题）：
  //   3 臂 × 3 次实测 —— OFF 无元数据 0/3、TITLE 放 Title 3/3、TOPIC 放 Topic 3/3。
  //   ⇒ 独立标签保留（与服务端同口径，且未观察到有害），但它是**保守写法**，
  //     不是「缺了就会坏」。别把它的必要性当既成事实。
  const topic = meta?.topic?.trim()
  if (topic) parts.push(`会议议题：${topic}。`)
  if (parts.length === 0) return ''
  return (
    '以下信息是**可信的上下文**，转写中与之高度相似的错误词组应按它纠正：' +
    parts.join('') +
    '\n注意：只按这份上下文纠正**明显对应**的错，**不要**把原文里的词替换成上下文里出现过、但并不对应的词。\n' +
    '**特别地**：转写里出现、但名单上没有的人名，**多半是正确的**（可能是列席者、临时加入的人、或没被记录进名单的人），**不要**把它换成名单里的另一个人名。\n'
  )
}