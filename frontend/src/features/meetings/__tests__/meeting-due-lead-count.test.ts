// §356 前缀档位族的行为锁定（第一族 + 第二族）。
//
// 为什么现在才写
// --------------
// §354/§355 定位了三族缺陷、§356 在 /tmp 验证了统一修法（33/33），
// 但**修法尚未落工作区** ⇒ 这批判据现在是红的。
// 它锁的是「缺陷赖以存在的前提」，而不是缺陷本身 ——
// 修法落地后它会转绿，而任何人再次改正则时它会重新变红。
//
// 锁的到底是什么
// --------------
// 不是「某个字符串必须被解析」（那是实现细节），
// 而是三件**语义不变式**：
//
//   ① 档位必须被**计数**：说「第 n 个下」就该推 n 档，不是 1 档、不是 2 档。
//   ② 未说前缀时行为**逐字不变**：裸「季度末」「月底」不许被前缀支抢走。
//   ③ 相邻形态**不回归**：上个月/下下周这些仍在工作里的答案不许变。
//
// ⚠ 这三条都不是「正则长什么样」，所以**换个实现也该照样通过**。
//
// 判读纪律（本会话真栽过的坑）
// ----------------------------
//  · 期望值全部**手工推算**，不从 parseDueAt 的输出反推；
//  · 注入固定 now ⇒ 任意时区/任意日期跑结果一致；
//  · **阳性对照**必须存在：若有人把整条分支改成返回 null，
//    所有负向断言都会变绿 —— 对照锁住「没全坏」。
import assert from 'node:assert/strict'
import { describe, it } from 'node:test'
import { parseDueAt } from '../meeting-due.ts'

// 2026-10-10 是周六。季度：Q4 = 10/1–12/31。
function now(): number {
  return new Date(2026, 9, 10, 12, 0).getTime()
}
function nowAt(y: number, m: number, d: number): number {
  return new Date(y, m - 1, d, 12, 0).getTime()
}

function day(at: number | undefined): string | null {
  if (at === undefined) return null
  const x = new Date(at)
  return `${x.getFullYear()}-${String(x.getMonth() + 1).padStart(2, '0')}-${String(x.getDate()).padStart(2, '0')}`
}

/** 同时断言「日」与「匹配串」——只断言日期会漏掉「算对了但匹配错的那一支」。 */
function expectAt(text: string, wantDay: string, wantMatched: string, at = now()) {
  const r = parseDueAt(text, at)
  assert.ok(r, `${text} 应当解析出时刻，实得 null`)
  assert.equal(day(r.at), wantDay, `${text} 的日期不对`)
  assert.equal(r.matchedText.trim(), wantMatched, `${text} 的 matchedText 不对（说明命中了另一支）`)
}

describe('§356 不变式 ①：档位必须被计数（月）', () => {
  // 手工推算：今天 2026-10-10。下个月=11月，下下个月=12月，下下下=2027-01。
  const cases: [string, string][] = [
    ['下个月底', '2026-11-30'],
    ['下下个月底', '2026-12-31'],
    ['下下个月初', '2026-12-01'],
    ['下下个月中', '2026-12-15'],
    ['下下下个月底', '2027-01-31'],
    ['下下下下个月底', '2027-02-28'],
  ]
  for (const [text, want] of cases) {
    it(`${text} ⇒ ${want}`, () => expectAt(text, want, text))
  }
})

describe('§356 不变式 ①：档位必须被计数（季度 / 年）', () => {
  // Q4 末 = 2026-12-31；下个季度末 = 2027-03-31；下下个 = 2027-06-30；下下下个 = 2027-09-30。
  const q: [string, string][] = [
    ['下个季度末', '2027-03-31'],
    ['下下个季度末', '2027-06-30'],
    ['下下下个季度末', '2027-09-30'],
  ]
  for (const [text, want] of q) {
    it(`${text} ⇒ ${want}`, () => expectAt(text, want, text))
  }
  // 年：2026-12-31 已过 ⇒ 「下个年底」= 2027-12-31。
  const y: [string, string][] = [
    ['下个年底', '2027-12-31'],
    ['下年底', '2027-12-31'],
    ['下下个年底', '2028-12-31'],
  ]
  for (const [text, want] of y) {
    it(`${text} ⇒ ${want}`, () => expectAt(text, want, text))
  }
})

describe('§356 不变式 ②：未说前缀时行为逐字不变', () => {
  // 阳性对照：若前缀支把裸串抢走，这三条会红。
  for (const [text, want, matched] of [
    ['季度末', '2026-12-31', '季度末'],
    ['年底', '2026-12-31', '年底'],
    ['十一月底前', '2026-11-30', '十一月底'],
    ['11月底', '2026-11-30', '11月底'],
  ] as [string, string, string][]) {
    it(`${text} 仍由裸串支命中`, () => expectAt(text, want, matched))
  }
})

describe('§356 不变式 ②：相邻形态不回归', () => {
  const same: [string, string, string][] = [
    ['下个月底', '2026-11-30', '下个月底'],
    ['下个月初', '2026-11-01', '下个月初'],
    ['下个月中', '2026-11-15', '下个月中'],
    ['月底', '2026-10-31', '月底'],
    ['本月底', '2026-10-31', '本月底'],
    ['月初', '2026-10-01', '月初'],
    ['月中', '2026-10-15', '月中'],
    // 第三族本轮**未修** —— 锁住现状，防止修第二族时顺手改坏它。
    ['下下周一', '2026-10-19', '下下周一'],
    ['下下周五', '2026-10-23', '下下周五'],
  ]
  for (const [text, want, matched] of same) {
    it(`${text} 不变`, () => expectAt(text, want, matched))
  }
})

describe('§356 不变式 ③：跨年 / 闰年 / 滚动边界', () => {
  // 2027 非闰年 ⇒ 2 月 28 天。
  it('2026-12 说「下下个月底」= 2027-02-28', () =>
    expectAt('下下个月底', '2027-02-28', '下下个月底', nowAt(2026, 12, 15)))
  it('2026-11-30 说「下下个月初」= 2027-01-01', () =>
    expectAt('下下个月初', '2027-01-01', '下下个月初', nowAt(2026, 11, 30)))
  // 「季度末」是**滚动**的：2026-12-15 时 Q4 末还没到 ⇒ 不滚；加一个「下个」才推进。
  it('2026-12-15「季度末」不滚', () =>
    expectAt('季度末', '2026-12-31', '季度末', nowAt(2026, 12, 15)))
  it('2026-12-15「下个季度末」推进一档', () =>
    expectAt('下个季度末', '2027-03-31', '下个季度末', nowAt(2026, 12, 15)))
  it('2026-07-10「下个季度末」= 2026-12-31', () =>
    expectAt('下个季度末', '2026-12-31', '下个季度末', nowAt(2026, 7, 10)))
  it('2026-01-10「下个季度末」= 2026-06-30', () =>
    expectAt('下个季度末', '2026-06-30', '下个季度末', nowAt(2026, 1, 10)))
})

describe('§356 阴性对照：缺粒度时不得凭空给出时刻', () => {
  for (const text of ['下个月', '下下月', '这周', '散会以后']) {
    it(`${text} 解析为 null`, () => {
      assert.equal(parseDueAt(text, now()), null, `${text} 不该解析出时刻`)
    })
  }
})