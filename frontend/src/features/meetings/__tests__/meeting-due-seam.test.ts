/**
 * meeting-due-seam.test.ts — §540：ASR **骑缝字**把时间点解析带偏的两种错法。
 *
 * ── 这道门守的缺口 ──
 *
 * 录音按段切，ASR 在切片边界上会吐出**骑缝字**（一个字被两片各认一半）：
 *
 *   P1  「明天下午点两点半」——时段词与钟点之间多一个「点」
 *       ⇒ `PERIOD_CLOCK_RE` 的 `\s*` 匹配不上 ⇒ 正则改从「两点半」起匹配
 *       ⇒ **时段词被静默丢弃** ⇒ `applyDayPeriod(undefined, 2)` = **02:30**
 *       （下午两点半 变成 凌晨两点半，**差 12 小时**）
 *
 *   P2  「明天下午2点点半」——钟点与分钟之间多一个「点」
 *       ⇒ 钟点定义与 `parseClockPart` 的 `^…$` 都匹配不上
 *       ⇒ 退化成只认整点 ⇒ **14:00**（「半」被静默丢掉，**差 30 分钟**）
 *
 * 实测（§540 修复前）：7 个骑缝句里 **0 个**解析正确，正常形态全对。
 *
 * ── 判据为什么用「配平」而不是拍脑袋的期望值 ──
 * 骑缝句必须与**去掉骑缝字的同一句**解析出同一时刻。
 * 第一版我给「上午点十点」写了「明天 10:00」这个期望值 —— 那是我编的，
 * 正确的判据是配平。第二组绝对基线单独留着，防止「配平地一起错」。
 *
 * ── 不在这道门里修的两件事（都不是技术缺陷）──
 *   · 裸钟点无日期锚（裸「两点」→ 凭空造出 10-14 02:00）⇒ **#34 的产品口径**待拍板；
 *   · 相邻双钟点「明天三点四点」→ 03:04 ⇒ 输入本身歧义，且修它会伤到
 *     「五点二十点」这类口语 ⇒ 只登记，不改。
 */

import { describe, it } from 'node:test'
import assert from 'node:assert/strict'
import { parseDueAt } from '../meeting-due.ts'

// 固定基准：周二 2026-10-13 10:00 +08:00
const NOW = new Date('2026-10-13T10:00:00+08:00').getTime()

const fmt = (at: number): string => {
  const d = new Date(at)
  const p = (n: number) => String(n).padStart(2, '0')
  return `${d.getMonth() + 1}-${p(d.getDate())} ${p(d.getHours())}:${p(d.getMinutes())}`
}
const at = (text: string): string | null => {
  const r = parseDueAt(text, NOW)
  return r ? fmt(r.at) : null
}

describe('ASR 骑缝字', () => {
  it('一处骑缝：时段词与钟点之间（修前差 12 小时）', () => {
    const cases: [string, string][] = [
      ['明天下午点两点半', '明天下午两点半'],
      ['明天下午点三点', '明天下午三点'],
      ['晚上点八点', '晚上八点'],
      ['上午点十点', '上午十点'],
      ['明天中午点十二点半', '明天中午十二点半'],
    ]
    for (const [seam, clean] of cases) {
      assert.equal(at(seam), at(clean), `「${seam}」应与「${clean}」同一时刻`)
      assert.notEqual(at(seam), null, `「${seam}」不该解析失败`)
    }
  })

  it('一处骑缝：钟点与分钟之间（修前差 30 分钟）', () => {
    const cases: [string, string][] = [
      ['明天下午2点点半', '明天下午2点半'],
      ['明天下午2点点20分', '明天下午2点20分'],
      ['上午10点点一刻', '上午10点一刻'],
      ['明天9点点三刻', '明天9点三刻'],
    ]
    for (const [seam, clean] of cases) {
      assert.equal(at(seam), at(clean), `「${seam}」应与「${clean}」同一时刻`)
    }
  })

  it('两处骑缝：宁可退回「只有日期」也不给静默错掉的分钟', () => {
    // 本文件的立场（meeting-due.ts 原注释）：宁可判 null，也不要半截钟点
    // 静默算错 30 分钟。这里期望值是**当天 09:00**（日期锚仍在、钟点被丢弃），
    // 而不是「下午3点」那种少 30 分钟的答案。
    for (const s of ['明天下午2点点点半', '明天三点点点半', '明天三点点点点半']) {
      assert.equal(at(s), '10-14 09:00', `「${s}」应当退回 09:00，而不是静默给一个错分钟的时刻`)
    }
  })

  it('两处骑缝不许连坐：后面还有正常钟点时要找到它', () => {
    assert.equal(at('明天三点点点半，四点开会'), '10-14 04:00')
    assert.equal(at('明天下午2点点点半，晚上八点'), '10-14 20:00')
  })
})

describe('绝对基线（防止配平地一起错）', () => {
  const cases: [string, string][] = [
    ['明天下午两点半', '10-14 14:30'],
    ['今天下午三点', '10-13 15:00'],
    ['晚上八点半', '10-13 20:30'],
    ['中午十二点半', '10-13 12:30'],
    ['下午3点20分', '10-13 15:20'],
    ['15:00', '10-13 15:00'],
    // 骑缝修复后的绝对值（不靠配平也能站住）
    ['明天下午点两点半', '10-14 14:30'],
    ['明天下午2点点半', '10-14 14:30'],
    ['明天下午2点点20分', '10-14 14:20'],
    ['上午10点点一刻', '10-13 10:15'],
  ]
  for (const [input, expect] of cases) {
    it(`「${input}」→ ${expect}`, () => {
      assert.equal(at(input), expect)
    })
  }
})

describe('否定用例：放宽不许把非时间表述吃进来', () => {
  for (const s of ['三十秒', '三号会议室', '推迟两天', '百分之十二']) {
    it(`「${s}」→ null`, () => {
      assert.equal(at(s), null)
    })
  }
})