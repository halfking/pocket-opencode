// meeting-due-silent-wrong-date.test.ts —— §390：**期限不许被静默答错一天**。
//
// ── 这道门守的是什么 ───────────────────────────────────────────────
//
// 用户需求：「将一些时间点自动加入到计划日程中」。
// `parseDueAt` 的产出直接进 `due_at` 与 `meeting-next-event.ts` 建的日程，
// 所以它答错的后果不是「没建日程」，而是**建了一条时刻错掉的日程** ——
// 而本仓自己的口径（`meeting-next-event.ts`）写着：
//
//   「建一条时刻错掉的日程比不建更糟」
//
// ── 原缺陷（2026-10-11 实测，基准 2026-10-07 周三 15:00）──────────────
//
//   输入「2026-10-9 14:00」→ 原答 **10/08 14:00**
//
//   成因两段：
//   ① 机器分支要求月/日补零（`\d{2}`），而中文分支不吃这一套（「10月9日」可以）
//      ⇒ **同一个日期，机器格式要求补零、中文格式不要求**；
//   ② `2026-10-9` 于是掉到「只有钟点」分支，那一支只要文本里有钟点就返回，
//      **不管旁边还留着没解析掉的日期** ⇒ 日期被静默丢弃，
//      只剩 14:00 落到「下一个 14:00」⇒ **比正确日期早一天**。
//
// ⚠ 最坏的一点：答出来的**不是空值**，是一个看起来完全合理的期限
// ⇒ 用户不会察觉 ⇒ 可能按错的日子赴约/交付。
//
// ── 两条纪律 ───────────────────────────────────────────────────────
//
//   ① 每条用例写明**为什么**是这个期望（不写「应该等于」这种废话）；
//   ② 必须有**阴性对照**：证明修复不是「一律返回 null」。
//      只钉「坏输入返回 null」的判据，会被「把整个函数改成 return null」满足。

import { test } from 'node:test'
import assert from 'node:assert/strict'
import { parseDueAt } from '../meeting-due.ts'

/** 2026-10-07 是周三，15:00。取「当天的钟点已过」是为了让裸钟点分支落到明天。 */
const NOW = new Date(2026, 9, 7, 15, 0, 0).getTime()

const fmt = (at: number) =>
  new Date(at).toLocaleString('zh-CN', {
    year: 'numeric', month: '2-digit', day: '2-digit', hour: '2-digit', minute: '2-digit',
  })

test('非补零的机器日期必须与补零等价（§390 的核心回归靶子）', () => {
  const a = parseDueAt('2026-10-9 14:00', NOW)!
  const b = parseDueAt('2026-10-09 14:00', NOW)!
  assert.ok(a, '非补零写法不该解析失败')
  // ⭐ 断言的是**两者相等**，而不是硬编码一个日期：
  //   这样将来基准日变了也不用改这里，且「补零那条被改坏」也会立刻红。
  assert.equal(a.at, b.at)
  assert.match(fmt(a.at), /10\/09.*14:00/)
})

test('月份也不要求补零（2026-1-9 ≡ 2026-01-09）', () => {
  const a = parseDueAt('2026-1-9', NOW)!
  assert.ok(a)
  assert.match(fmt(a.at), /2026\/01\/09/)
})

test('认不出的日期 + 钟点 ⇒ fail-closed 返回 null，而不是错一天', () => {
  // 「10/09」与「10-09」这两种写法解析器不支持。
  // ⚠ 修法**不是**去支持它们（那是格式口径决策），
  //   而是按本文件既有哲学 fail-closed：宁可没有期限，也不要一条错的日程。
  for (const s of ['10/09 14:00', '10-09 14:00']) {
    assert.equal(parseDueAt(s, NOW), null, `${s} 不该被静默答成一个日期`)
  }
})

test('越界的日历日期被拒（2026-02-30 会被 JS 静默溢出成 3-02）', () => {
  assert.equal(parseDueAt('2026-02-30', NOW), null)
  assert.equal(parseDueAt('2026-13-01', NOW), null, '13 月不存在')
})

test('⭐ 阴性对照：裸钟点这一支仍然要能答（修复不是「一律 return null」）', () => {
  // 基准是 15:00 ⇒ 14:00 已过 ⇒ 「下一个 14:00」是明天 10/08。
  // ⚠ 若有人把第 4 支整个关掉，这条会红 —— 那就是把能力砍了，不是修复。
  const r = parseDueAt('14:00', NOW)!
  assert.ok(r, '裸钟点必须仍能解析')
  assert.match(fmt(r.at), /10\/08.*14:00/)
})

test('⭐ 阴性对照：中文表达带钟点时不受新增守卫影响', () => {
  // 这几条在守卫加入前后必须**逐字相同** ——
  // 守卫的形状是「摘掉钟点后还剩日期样碎片就 return null」，
  // 而这些输入的日期都被**更早的分支**消费掉了，rest 里不该剩任何东西。
  assert.match(fmt(parseDueAt('周五 14:00', NOW)!.at), /10\/09.*14:00/)
  assert.match(fmt(parseDueAt('下周一 14:00', NOW)!.at), /10\/12.*14:00/)
  assert.match(fmt(parseDueAt('10月9日 14:00', NOW)!.at), /10\/09.*14:00/)
  assert.match(fmt(parseDueAt('20号 14:00', NOW)!.at), /10\/20.*14:00/)
})

test('时间区间不该被新守卫误伤（10:00-12:00 的后半段不是日期）', () => {
  // ⚠ 「-12:00」里没有「数字-数字」的形状 ⇒ 守卫不能把它当成「10/09」那类残留碎片。
  const r = parseDueAt('10:00-12:00', NOW)
  assert.ok(r, '区间写法不该被守卫吞掉')
})
// ─────────────────────────────────────────────────────────────────────
// §392：**类级**性质 —— 任何分支都不得「返回了结果却留着没消费掉的日期」
//
// §390 修的是「只有钟点」那一支。但同一个失效形态（**返回了一个值，
// 而文本里的日期被静默丢弃**）理论上可以出现在别的支上。
// ⇒ 这条用例把 54 条抽样里的**全部**返回非 null 的输入都过一遍，
//   断言「matchedText 把日期样碎片都吃掉了」。
//
// ⚠⚠ 探针首版按**原文**做 replace(matchedText)，而解析器返回的 matchedText
//   **已去掉空格**、原文却带空格 ⇒ 替换落空 ⇒ 整串都算「残留」⇒ 假阳性。
//   ⇒ 两边都要先 `strip(s => s.replace(/\s+/g,''))` 再比。
//
// ⚠ 这条性质自带一个**口径**（DATEY 这个正则），它会有假阳性 —— 但方向是安全的：
//   假阳性只会让门**响**，由人复核；反过来若把正则收窄，漏报才是真的看不见。

const DATEY = /\d{1,4}\s*[-/.]\s*\d{1,2}|\d{1,4}\s*月|\d{1,2}\s*[日号]|[一二两三四五六七八九十]+\s*月/
const strip = (s) => s.replace(/\s+/g, '')

const SWEEP = [
  '2026-10-09', '2026-10-9', '10/09', '10-09', '2026/10/09', '12.10', '2026.10.09', '20261009',
  '十月九日', '9号', '9日', '周五', '这周五', '明天', '后天', '3天后', '下个月初', '十一月底',
  '月底', '季末', '年底', '下午三点', '明天上午十点', '下周一 14:00', '9号下午两点', '十月九号',
  '2026-10-9 14:00', '10/09 14:00', '3/4', '2026-10-09 09:00',
  '10/9', '10-9', '2026/10/9', '下月5号', '本周三之前', '周五晚上8点', '下周五17:00前',
  '九月十日', '下月十五', '十月一号', '2026年10月9日', '10月9号 上午十点', '九号 14:00',
  '下个月9号', '三十号', '下周三 10:00', '周五17:00前', '明天 9:00 前', '10月', '9月', '十号',
]

test('§392 · 类级性质：没有哪一支会「返回结果却丢掉日期」', () => {
  const offenders = []
  for (const s of SWEEP) {
    const r = parseDueAt(s, NOW)
    if (!r) continue
    const rest = strip(s).replace(strip(r.matchedText), '')
    if (DATEY.test(rest)) {
      offenders.push(`${JSON.stringify(s)} → ${fmt(r.at)}（命中 ${JSON.stringify(r.matchedText)}，残留 ${JSON.stringify(rest)}）`)
    }
  }
  assert.equal(
    offenders.length, 0,
    '下列输入返回了一个时刻，但文本里的日期没有被 consumed ⇒ 用户会拿到一个错的日子：\n' +
      offenders.join('\n'),
  )
})

test('§392 · 抽样规模被登记（避免「扫了 3 条就说覆盖」）', () => {
  // 这条用例不测行为，测**覆盖面声明**本身：
  // 有人日后把 SWEEP 砍到只剩 §390 那几条时，这一条会提醒他覆盖面缩了。
  assert.ok(SWEEP.length >= 50, `抽样只剩 ${SWEEP.length} 条，覆盖面比 §392 记录的小`)
})
